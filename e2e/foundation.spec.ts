import {openLegacyProject} from './legacyFixture';
import { test, expect } from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs/promises';

test('design, image import, archive download/reopen and preview use one model', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await openLegacyProject(page);
  await page.getByLabel('Project name', { exact: true }).fill('Café — Studio');
  await page.getByRole('button', { name: 'Add container', exact: true }).click();
  await page.getByLabel('Layer name', { exact: true }).fill('Hero section');
  await page.getByLabel('Layer name', { exact: true }).press('Tab');
  await page.getByLabel('Padding', { exact: true }).fill('48');
  await page.getByLabel('Padding', { exact: true }).press('Tab');
  await page.getByLabel('Background', { exact: true }).fill('#edf2e8');
  await page.getByLabel('Background', { exact: true }).press('Tab');
  await page.getByRole('button', { name: 'Add text', exact: true }).click();
  await page.getByLabel('Text content', { exact: true }).fill('Ideas deserve\na little room.');
  await page.getByLabel('Text content', { exact: true }).press('Tab');
  await page.getByLabel('Font size', { exact: true }).fill('64');
  await page.getByLabel('Font size', { exact: true }).press('Tab');
  await page.getByLabel('Weight', { exact: true }).selectOption('600');
  await page.getByRole('button', { name: 'Add text', exact: true }).click();
  await page.getByLabel('Text content', { exact: true }).fill('A local creative studio. Made for the way you think.');
  await page.getByLabel('Text content', { exact: true }).press('Tab');
  await page.getByLabel('Font size', { exact: true }).fill('20');
  await page.getByLabel('Font size', { exact: true }).press('Tab');
  // Real raster bytes go through FileReader, asset validation, blob rendering and archive encoding.
  await page.getByLabel('Import image file').setInputFiles({ name: 'Niño.png', mimeType: 'image/png', buffer: await fs.readFile('e2e/fixtures/local-art.png') });
  await expect(page.getByTestId('artboard').getByRole('img')).toHaveCount(1);
  await page.getByLabel('Alt text', { exact: true }).fill('Local image');
  await page.getByLabel('Alt text', { exact: true }).press('Tab');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const download = await downloadPromise;
  const savedFile = testInfo.outputPath('Café Studio.forma');
  await download.saveAs(savedFile);
  await fs.mkdir(path.resolve('examples'), { recursive: true });
  await fs.copyFile(savedFile, path.resolve('examples/Studio.forma'));
  expect((await fs.stat(savedFile)).size).toBeGreaterThan(500);
  await expect(page.getByTestId('save-status')).toContainText('Saved');
  const fileChooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Open project', exact: true }).click();
  await (await fileChooser).setFiles(savedFile);
  await expect(page.getByTestId('artboard')).toContainText('Ideas deserve');
  await expect(page.getByTestId('artboard').getByRole('img', { name: 'Local image' })).toBeVisible();
  await page.getByRole('button', { name: 'Fit page', exact: true }).click();
  await fs.mkdir(path.resolve('docs/screenshots'), { recursive: true });
  await page.screenshot({ path: 'docs/screenshots/foundation-editor.png' });
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(page.getByTestId('selection-label')).toHaveCount(0);
  await page.getByRole('button', { name: 'Phone viewport', exact: true }).click();
  await expect(page.getByLabel('Preview width', { exact: true })).toHaveValue('390');
  await expect(page.getByTestId('artboard')).toContainText('Ideas deserve');
  expect(errors).toEqual([]);
});

test('recovers unsaved edits after reload and can discard them for a new project', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Project name', { exact: true }).fill('Recover this studio');
  await page.getByRole('button', { name: 'Add text', exact: true }).click();
  await page.getByLabel('Text content', { exact: true }).fill('Work worth keeping');
  await page.getByLabel('Text content', { exact: true }).press('Tab');
  await expect(page.locator('.statusbar')).toContainText('Recovery snapshot updated');
  page.once('dialog', dialog => dialog.accept());
  await page.reload();
  await page.getByRole('button', { name: 'Recover project', exact: true }).click();
  await expect(page.getByLabel('Project name', { exact: true })).toHaveValue('Recover this studio');
  await expect(page.getByTestId('artboard')).toContainText('Work worth keeping');
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox').fill('Fresh studio');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.getByRole('button', { name: 'Discard and continue', exact: true }).click();
  await expect(page.getByLabel('Project name', { exact: true })).toHaveValue('Fresh studio');
  await expect(page.getByTestId('artboard')).not.toContainText('Work worth keeping');
});
